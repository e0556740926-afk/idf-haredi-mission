/** Arc between two map points (bulging "north", like a flight path). */
export const routePath = (a: [number, number], b: [number, number]) => {
  const [x1, y1] = project(a);
  const [x2, y2] = project(b);
  const dist = Math.hypot(x2 - x1, y2 - y1);
  const mx = (x1 + x2) / 2;
  const my = (y1 + y2) / 2 - dist * 0.28;
  return { d: `M${x1},${y1} Q${mx},${my} ${x2},${y2}`, p0: [x1, y1], c: [mx, my], p1: [x2, y2] } as const;
};

/** Point + tangent angle on a quadratic Bézier. */
export const quadAt = (p0: readonly number[], c: readonly number[], p1: readonly number[], t: number) => {
  const u = 1 - t;
  const x = u * u * p0[0] + 2 * u * t * c[0] + t * t * p1[0];
  const y = u * u * p0[1] + 2 * u * t * c[1] + t * t * p1[1];
  const dx = 2 * u * (c[0] - p0[0]) + 2 * t * (p1[0] - c[0]);
  const dy = 2 * u * (c[1] - p0[1]) + 2 * t * (p1[1] - c[1]);
  return { x, y, angle: (Math.atan2(dy, dx) * 180) / Math.PI };
};
